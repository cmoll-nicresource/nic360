/**
 * Converts the licensed Adobe Stock icon SVGs in icons/ into React
 * components in src/components/brandIcons.tsx.
 *
 * Usage: drop more <Name>.svg files into icons/, then run
 *   npx tsx scripts/importIcons.ts
 * to regenerate the component file. Safe to re-run any time.
 *
 * Each source SVG defines its two fill colors as `.cls-1`/`.cls-2` classes
 * in a <style> block. Inlining many of these on one page as-is would mean
 * every icon's "cls-1"/"cls-2" collide (same generic class names, last one
 * in the DOM wins), so this strips the <style> block and bakes each class's
 * color into a `fill="..."` attribute directly instead. The darker of an
 * icon's colors maps to --nrc-primary-dark and the lighter to
 * --nrc-secondary — classified by actual luminance, not by which class
 * number happened to get which color (the three source packs these came
 * from don't agree on that).
 */
import fs from 'fs'
import path from 'path'

const ICONS_DIR = path.join(process.cwd(), 'icons')
const OUTPUT_FILE = path.join(process.cwd(), 'src/components/brandIcons.tsx')

function hexLuminance(hex: string): number {
  const h = hex.replace('#', '')
  const r = parseInt(h.slice(0, 2), 16)
  const g = parseInt(h.slice(2, 4), 16)
  const b = parseInt(h.slice(4, 6), 16)
  return (0.299 * r + 0.587 * g + 0.114 * b) / 255
}

function toComponentName(filename: string): string {
  const base = filename.replace(/\.svg$/i, '')
  const pascal = base
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join('')
  return `${pascal}Icon`
}

type Converted = { name: string; viewBox: string; body: string }

function convertSvg(filePath: string): Converted {
  const raw = fs.readFileSync(filePath, 'utf-8')

  const viewBoxMatch = raw.match(/viewBox="([^"]+)"/)
  if (!viewBoxMatch) throw new Error(`No viewBox found in ${filePath}`)
  const viewBox = viewBoxMatch[1]

  const classColors = new Map<string, string>()
  const classRegex = /\.cls-(\d+)\s*\{\s*fill:\s*(#[0-9a-fA-F]{3,6});?\s*\}/g
  let m: RegExpExecArray | null
  while ((m = classRegex.exec(raw))) {
    classColors.set(m[1], m[2])
  }
  if (classColors.size === 0) throw new Error(`No .cls-N { fill } definitions found in ${filePath}`)

  const classVar = new Map<string, string>()
  const entries = [...classColors.entries()]
  if (entries.length === 1) {
    classVar.set(entries[0][0], 'var(--nrc-primary-dark)')
  } else {
    const sorted = entries.sort((a, b) => hexLuminance(a[1]) - hexLuminance(b[1]))
    classVar.set(sorted[0][0], 'var(--nrc-primary-dark)')
    classVar.set(sorted[sorted.length - 1][0], 'var(--nrc-secondary)')
  }

  let body = raw.replace(/<\?xml[^>]*\?>\s*/, '').replace(/<defs>[\s\S]*?<\/defs>\s*/, '')

  const innerMatch = body.match(/<svg[^>]*>([\s\S]*)<\/svg>/)
  if (!innerMatch) throw new Error(`Could not extract inner SVG content from ${filePath}`)
  body = innerMatch[1].trim()

  for (const [cls, cssVar] of classVar) {
    body = body.replaceAll(`class="cls-${cls}"`, `fill="${cssVar}"`)
  }

  return { name: toComponentName(path.basename(filePath)), viewBox, body }
}

function main() {
  if (!fs.existsSync(ICONS_DIR)) {
    console.log('No icons/ directory found — nothing to do.')
    return
  }

  const files = fs.readdirSync(ICONS_DIR).filter((f) => f.toLowerCase().endsWith('.svg'))
  if (files.length === 0) {
    console.log('No SVGs found in icons/ — nothing to do.')
    return
  }

  const icons = files.map((f) => convertSvg(path.join(ICONS_DIR, f))).sort((a, b) => a.name.localeCompare(b.name))

  const header = `// GENERATED by scripts/importIcons.ts from icons/*.svg — do not hand-edit.
// Re-run \`npx tsx scripts/importIcons.ts\` after adding/removing source SVGs.
import React from 'react'

import type { IconProps } from './icons'
`

  const components = icons
    .map(
      ({ name, viewBox, body }) => `export function ${name}({ className }: IconProps) {
  return (
    <svg viewBox="${viewBox}" className={className} aria-hidden="true">
      ${body}
    </svg>
  )
}`,
    )
    .join('\n\n')

  fs.writeFileSync(OUTPUT_FILE, `${header}\n${components}\n`)
  console.log(`Wrote ${icons.length} icon component(s) to ${path.relative(process.cwd(), OUTPUT_FILE)}:`)
  for (const icon of icons) console.log(`  - ${icon.name}`)
}

main()
